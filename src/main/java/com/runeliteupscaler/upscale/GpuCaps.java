package com.runeliteupscaler.upscale;

/**
 * A-04: GPU and driver capabilities that backends check in {@link Upscaler#isSupported}.
 * Filled from the GL context at startup; plain values so tests can build one.
 */
public final class GpuCaps
{
	public final String renderer;
	public final String version;
	public final boolean openGL43;

	public GpuCaps(String renderer, String version, boolean openGL43)
	{
		this.renderer = renderer;
		this.version = version;
		this.openGL43 = openGL43;
	}
}
